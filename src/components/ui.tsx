// ------------------------------------------------------------------ formatting
export const fmtMoney = (v: number, digits = 2) =>
  `$${v.toLocaleString('en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits })}`;

export const fmtPct = (v: number, digits = 1) => `${(v * 100).toFixed(digits)}%`;

/** All dataset timestamps are UTC; render them explicitly as UTC to avoid ambiguity. */
export const fmtDateTimeUtc = (iso: string) => {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return `${d.toISOString().slice(0, 10)} ${d.toISOString().slice(11, 19)} UTC`;
};

// ------------------------------------------------------------------ category icons
export function categoryIcon(category: string): React.ElementType {
  const c = category.toLowerCase();
  if (/jewel|luxury|gold|watch/.test(c)) return Gem;
  if (/elec|tech|phone|computer/.test(c)) return Tv;
  if (/digital|game|stream|soft|app|crypto/.test(c)) return Gamepad2;
  if (/rest|dine|food_dining|food|cafe|bar/.test(c)) return Utensils;
  if (/travel|air|flight|hotel/.test(c)) return Plane;
  if (/gas|fuel|petrol/.test(c)) return Fuel;
  if (/atm|cash|withdraw|bank/.test(c)) return Landmark;
  if (/grocery|supermarket/.test(c)) return ShoppingCart;
  if (/pharm|drug/.test(c)) return Pill;
  if (/health|fitness|medical/.test(c)) return HeartPulse;
  if (/home|furn/.test(c)) return Home;
  if (/auto|car|transport/.test(c)) return Car;
  if (/apparel|cloth|fashion/.test(c)) return Shirt;
  if (/shopping|retail|misc/.test(c)) return ShoppingBag;
  return Store;
}

// ------------------------------------------------------------------ badges
const badgeBase = 'inline-flex items-center gap-1 rounded-md border px-1.5 py-0.5 text-xs font-semibold uppercase tracking-wide whitespace-nowrap';

export type ProvenanceKind = 'simulated' | 'synthetic' | 'predicted' | 'confirmed' | 'measured' | 'estimated' | 'historical' | 'manual';

const PROVENANCE: Record<ProvenanceKind, { label: string; cls: string; icon: React.ElementType; title: string }> = {
  simulated: { label: 'Simulated', icon: Radio, cls: 'bg-violet-50 text-violet-700 border-violet-200 dark:bg-violet-500/15 dark:text-violet-300 dark:border-violet-500/30', title: 'Generated by a simulation – not a real or historical event.' },
  synthetic: { label: 'Synthetic sample', icon: FlaskConical, cls: 'bg-violet-50 text-violet-700 border-violet-200 dark:bg-violet-500/15 dark:text-violet-300 dark:border-violet-500/30', title: 'Bundled seeded synthetic dataset used for demonstration.' },
  predicted: { label: 'Predicted', icon: BrainCircuit, cls: 'bg-blue-50 text-blue-700 border-blue-200 dark:bg-[#3988FF]/15 dark:text-blue-300 dark:border-[#3988FF]/35', title: 'Model output – a prediction, not an outcome.' },
  confirmed: { label: 'Confirmed', icon: BadgeCheck, cls: 'bg-slate-100 text-slate-700 border-slate-300 dark:bg-slate-500/15 dark:text-slate-200 dark:border-slate-500/30', title: 'Ground-truth outcome from the dataset label.' },
  measured: { label: 'Measured', icon: Gauge, cls: 'bg-emerald-50 text-emerald-700 border-emerald-200 dark:bg-emerald-500/15 dark:text-emerald-300 dark:border-emerald-500/30', title: 'Computed from the held-out labelled test split.' },
  estimated: { label: 'Estimated', icon: Calculator, cls: 'bg-amber-50 text-amber-800 border-amber-200 dark:bg-amber-500/15 dark:text-amber-300 dark:border-amber-500/30', title: 'Depends on user-set cost assumptions.' },
  manual: { label: 'Manual test', icon: ClipboardCheck, cls: 'bg-sky-50 text-sky-800 border-sky-200 dark:bg-sky-500/15 dark:text-sky-300 dark:border-sky-500/30', title: 'Entered by hand on the Manual Transaction page. No real outcome; never used for training or evaluation.' },
  historical: { label: 'Historical', icon: BadgeCheck, cls: 'bg-slate-100 text-slate-700 border-slate-300 dark:bg-slate-500/15 dark:text-slate-200 dark:border-slate-500/30', title: 'Replayed from the uploaded historical dataset.' },
};

export const ProvenanceBadge: React.FC<{ kind: ProvenanceKind; label?: string }> = ({ kind, label }) => {
  const p = PROVENANCE[kind];
  const Icon = p.icon;
  return (
    <span className={`${badgeBase} ${p.cls}`} title={p.title}>
      <Icon className="w-3 h-3" aria-hidden="true" />
      {label ?? p.label}
    </span>
  );
};

/** Data-origin badge for a transaction row. */
export const OriginBadge: React.FC<{ origin: Transaction['origin'] }> = ({ origin }) => {
  if (origin === 'manual_entry') return <ProvenanceBadge kind="manual" />;
  if (origin === 'synthetic_stream') return <ProvenanceBadge kind="simulated" />;
  if (origin === 'synthetic_sample') return <ProvenanceBadge kind="synthetic" label="Synthetic" />;
  return <ProvenanceBadge kind="historical" label="Uploaded" />;
};

export const PredictionBadge: React.FC<{ probability: number; threshold: number; compact?: boolean }> = ({ probability, threshold, compact }) => {
  const flagged = probability >= threshold;
  return (
    <span
      className={`${badgeBase} ${
        flagged
          ? 'bg-amber-50 text-amber-800 border-amber-300 dark:bg-amber-500/15 dark:text-amber-300 dark:border-amber-500/40'
          : 'bg-emerald-50 text-emerald-700 border-emerald-200 dark:bg-emerald-500/10 dark:text-emerald-300 dark:border-emerald-500/30'
      }`}
      title={`Predicted by the model: probability ${(probability * 100).toFixed(1)}% ${flagged ? '≥' : '<'} threshold τ = ${threshold.toFixed(2)} (${flagged ? 'Flagged' : 'Clear'})`}
    >
      <BrainCircuit className="w-3 h-3" aria-hidden="true" />
      {compact ? '' : 'Predicted · '}
      {flagged ? 'Suspicious' : 'Legitimate'}
    </span>
  );
};

export const OutcomeBadge: React.FC<{ label: FraudLabel }> = ({ label }) => {
  if (label === null) {
    return (
      <span className={`${badgeBase} bg-slate-50 text-slate-600 border-dashed border-slate-300 dark:bg-transparent dark:text-slate-400 dark:border-slate-600`} title="No ground-truth label available (unlabelled or simulated).">
        <HelpCircle className="w-3 h-3" aria-hidden="true" />
        Pending / Unknown
      </span>
    );
  }
  return label === 1 ? (
    <span className={`${badgeBase} bg-red-50 text-red-700 border-red-200 dark:bg-[#E5484D]/15 dark:text-red-300 dark:border-[#E5484D]/40`} title="Ground-truth label: fraud">
      <BadgeCheck className="w-3 h-3" aria-hidden="true" />
      Confirmed Fraud
    </span>
  ) : (
    <span className={`${badgeBase} bg-emerald-50 text-emerald-700 border-emerald-200 dark:bg-emerald-500/10 dark:text-emerald-300 dark:border-emerald-500/30`} title="Ground-truth label: legitimate">
      <BadgeCheck className="w-3 h-3" aria-hidden="true" />
      Confirmed Legitimate
    </span>
  );
};

