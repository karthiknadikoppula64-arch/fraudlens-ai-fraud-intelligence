export const RiskMeter: React.FC<{ probability: number; threshold: number }> = ({ probability, threshold }) => {
  const color = probability >= Math.max(threshold, 0.7) ? 'bg-[#E5484D]' : probability >= threshold ? 'bg-amber-500' : 'bg-emerald-500';
  const text = probability >= Math.max(threshold, 0.7) ? 'text-red-600 dark:text-red-400' : probability >= threshold ? 'text-amber-700 dark:text-amber-400' : 'text-emerald-700 dark:text-emerald-400';
  return (
    <span className="inline-flex items-center gap-2 font-mono tabular-nums">
      <span className={`font-bold ${text}`}>{(probability * 100).toFixed(1)}%</span>
      <span className="w-12 h-1.5 rounded-full bg-slate-200 dark:bg-slate-700 overflow-hidden" aria-hidden="true">
        <span className={`block h-full ${color}`} style={{ width: `${Math.min(100, probability * 100)}%` }} />
      </span>
    </span>
  );
};

